import { config } from './config';
import { classifyImage, manipulationProbability } from './huggingface';
import type { MediaVerdict, PhotoAnalysis, RiskLevel } from './types';

const DISCLAIMER =
  'Media-forensics models are probabilistic. A result here is evidence, not proof - heavy compression, filters, screenshots and re-encoding can all push a genuine photo towards a "manipulated" score.';

function level(score: number): RiskLevel {
  if (score >= 70) return 'high';
  if (score >= 40) return 'medium';
  return 'low';
}

function explain(task: MediaVerdict['task'], probability: number | null, top: string | null): string {
  if (probability === null) {
    return `The model returned the label "${top ?? 'unknown'}" but its label vocabulary could not be mapped to a real/fake decision.`;
  }
  const pct = Math.round(probability * 100);
  if (task === 'ai-generated-image') {
    if (pct >= 70) return `Strong indicators that this image was fully generated by an AI image model (${pct}% synthetic-leaning).`;
    if (pct >= 40) return `Mixed signals. The detector leans ${pct}% towards synthetic generation, which is not conclusive.`;
    return `The detector found mostly camera-like characteristics (${100 - pct}% towards a real photograph).`;
  }
  if (pct >= 70) return `Strong indicators of face manipulation / face-swap artefacts (${pct}% manipulation-leaning).`;
  if (pct >= 40) return `Ambiguous. ${pct}% of the signal points to facial manipulation, which warrants manual review.`;
  return `No significant face-manipulation artefacts detected (${100 - pct}% towards an unmanipulated face).`;
}

async function runModel(
  task: MediaVerdict['task'],
  model: string,
  bytes: Uint8Array,
  mime: string,
): Promise<MediaVerdict> {
  try {
    const labels = await classifyImage(model, bytes, mime);
    const probability = manipulationProbability(labels);
    const topLabel = labels[0]?.label ?? null;
    return {
      task,
      model,
      available: true,
      topLabel,
      manipulationProbability: probability,
      labels,
      explanation: explain(task, probability, topLabel),
    };
  } catch (error) {
    return {
      task,
      model,
      available: false,
      topLabel: null,
      manipulationProbability: null,
      labels: [],
      explanation: 'This detector did not return a result, so it was excluded from the verdict.',
      error: (error as Error).message,
    };
  }
}

export async function analyzePhoto(
  bytes: Uint8Array,
  mime: string,
  fileName: string,
): Promise<PhotoAnalysis> {
  const [aiGen, deepfake] = await Promise.all([
    runModel('ai-generated-image', config.hf.aiGenModel, bytes, mime),
    runModel('face-manipulation', config.hf.deepfakeModel, bytes, mime),
  ]);

  const verdicts = [aiGen, deepfake];
  const usable = verdicts.filter((v) => v.available && v.manipulationProbability !== null);

  if (usable.length === 0) {
    const reasons = verdicts.map((v) => `${v.model}: ${v.error ?? 'no usable labels'}`).join(' | ');
    throw new Error(`No image-forensics model returned a usable result. ${reasons}`);
  }

  const peak = Math.max(...usable.map((v) => v.manipulationProbability as number));
  const score = Math.round(peak * 100);
  const confidence = usable.length > 1 ? Math.min(...usable.map((v) => Math.abs((v.manipulationProbability as number) - 0.5) * 2 )) : Math.abs(peak - 0.5) * 2;

  const leading = usable.find((v) => v.manipulationProbability === peak)!;
  const summary =
    score >= 70
      ? `At least one forensics model flags this image as likely ${leading.task === 'ai-generated-image' ? 'AI-generated' : 'face-manipulated'}.`
      : score >= 40
        ? 'The detectors disagree or are uncertain. Treat this image as unverified and look for a trusted original source.'
        : 'No strong manipulation signal was found, but this does not certify the image as authentic.';

  return {
    kind: 'photo',
    risk: level(score),
    score,
    confidence: Number(confidence.toFixed(2)),
    summary,
    verdicts,
    fileName,
    fileSize: bytes.byteLength,
    recommendedActions: [
      'Reverse-image search the photo to find its earliest published source.',
      'Check for a credible original publisher before resharing.',
      'Look for physical giveaways: hands, teeth, jewellery, text in the background, lighting mismatches.',
      'If the image is used in a money or romance request, treat it as untrusted regardless of this score.',
    ],
    disclaimer: DISCLAIMER,
    createdAt: new Date().toISOString(),
  };
}
